import { Button, PanelLink } from '@pterodactyl/sdk';
import type { ViewProps } from '@pterodactyl/sdk/theme';
import AuthCard, { Field, authLinkClass } from '../AuthCard';

export default function Checkpoint({ model, className }: ViewProps<'page.auth.checkpoint'>) {
    const { recovery } = model;

    return (
        <AuthCard title={recovery ? 'Recovery Code' : 'Two-Factor Check'} submit={model.submit} className={className}>
            <Field
                field={model.fields.code}
                label={recovery ? 'Recovery Code' : 'Authentication Code'}
                description={
                    recovery
                        ? 'Enter one of the recovery codes generated when you set up two-factor authentication.'
                        : 'Enter the code generated by your authenticator device.'
                }
                autoFocus
            />
            <Button type='submit' size='xlarge' disabled={!model.canSubmit} isLoading={model.submitting}>
                Continue
            </Button>
            <div className='text-center'>
                <button
                    type='button'
                    onClick={model.toggleRecovery}
                    className='cursor-pointer appearance-none border-0 bg-transparent p-0 fs-tiny text-ink-muted tracking-widest uppercase no-underline transition-colors hover:text-foreground'
                >
                    {recovery ? 'I Have My Device' : "I've Lost My Device"}
                </button>
            </div>
            <div className='text-center'>
                <PanelLink destination={model.login} className={authLinkClass}>
                    Back to sign in
                </PanelLink>
            </div>
        </AuthCard>
    );
}
